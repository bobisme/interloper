#!/usr/bin/env bash
# Regenerate crates/interloper/src/providers/mod.rs from the adapter files on
# disk. Every `<name>.rs` except mod.rs and util.rs is a provider module that
# exports `SPEC`. Run from a checkout or workspace root:
#     scripts/gen-providers-mod.sh [ROOT]
set -euo pipefail
root=${1:-.}
dir="$root/crates/interloper/src/providers"
mods=$(find "$dir" -maxdepth 1 -name '*.rs' ! -name mod.rs ! -name util.rs -printf '%f\n' | sed 's/\.rs$//' | LC_ALL=C sort)
{
  echo '//! Every built-in backend. One module per backend; its `SPEC` goes in [`all`].'
  echo '//! Generated by scripts/gen-providers-mod.sh; rerun it after adding a module.'
  echo
  for m in $mods; do echo "pub mod $m;"; done
  echo 'pub mod util;'
  echo
  echo 'use crate::registry::ProviderSpec;'
  echo
  echo '/// The compiled-in provider table.'
  echo 'pub fn all() -> Vec<ProviderSpec> {'
  echo '    vec!['
  for m in $mods; do echo "        $m::SPEC,"; done
  echo '    ]'
  echo '}'
} > "$dir/mod.rs.new"
mv "$dir/mod.rs.new" "$dir/mod.rs"
